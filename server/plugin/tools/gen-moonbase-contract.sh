#!/bin/bash
# Writes Configuration/moonbase-contract.txt: what the Tortugarr app uses from the Moonbase
# (Moonfin) server plugin - the settings keys it syncs and the /Moonfin/... routes it calls.
# MoonbaseGate holds a new Moonbase version back when it drops any of these that the approved
# version had (Moonbase 2.5.0 dropped "backdropEnabled", 2026-10-30). Run after changing
# lib/data/services/synced_fields.dart or a /Moonfin/ call in the app, then rebuild the plugin.
set -euo pipefail
cd "$(dirname "$0")/../../.."
out=server/plugin/Jellyfin.Plugin.Tortugarr/Configuration/moonbase-contract.txt
{
  echo "# Generated by server/plugin/tools/gen-moonbase-contract.sh - do not edit."
  {
    rg -o --no-filename "SyncedField\('[A-Za-z0-9_]+'" lib/data/services/synced_fields.dart | sed "s/SyncedField('//;s/'//"
    rg -o --no-filename "/Moonfin/[A-Za-z]+(/[A-Za-z]+)?" lib --type dart -g '!lib/l10n/**' | sed 's:^/::' |
      awk -F/ '{print $1"/"$2; if (NF>2) print $3}'
  } | sort -u
} > "$out"
echo "wrote $out ($(($(wc -l < "$out") - 1)) entries)"
